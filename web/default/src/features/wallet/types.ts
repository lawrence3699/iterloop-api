/**
 * Generic API response
 */
export interface ApiResponse<T = unknown> {
  success?: boolean
  message?: string
  data?: T
}

/**
 * Standard API response types
 */
export type TopupInfoResponse = ApiResponse<TopupInfo>
export type RedemptionResponse = ApiResponse<number>
export type AmountResponse = ApiResponse<string>
export type PaymentResponse = ApiResponse<Record<string, unknown>> & {
  url?: string
}
export type StripePaymentResponse = ApiResponse<{ pay_link: string }>
export type AffiliateCodeResponse = ApiResponse<string>
export type AffiliateTransferResponse = ApiResponse
export type CreemPaymentResponse = ApiResponse<{ checkout_url: string }>
export type WaffoPaymentResponse = ApiResponse<
  { payment_url?: string } | string
>
export type WaffoPancakePaymentResponse = ApiResponse<
  | {
      checkout_url?: string
      session_id?: string
      expires_at?: number | string
      order_id?: string
      // Self-service session token + expiry — surfaced by the backend so
      // future flows (refund / cancel from new-api's own UI) can use them
      // without re-issuing checkout. Not consumed by the current handler.
      token?: string
      token_expires_at?: number | string
    }
  | string
>

/**
 * Creem product configuration
 */
export interface CreemProduct {
  /** Product display name */
  name: string
  /** Creem product ID */
  productId: string
  /** Product price */
  price: number
  /** Quota amount to credit */
  quota: number
  /** Currency (USD or EUR) */
  currency: 'USD' | 'EUR'
}

/**
 * Creem payment request
 */
export interface CreemPaymentRequest {
  /** Creem product ID */
  product_id: string
  /** Payment method identifier */
  payment_method: 'creem'
}

/**
 * Payment method configuration
 */
export interface PaymentMethod {
  /** Display name of payment method */
  name: string
  /** Payment method type identifier */
  type: string
  /** Legacy optional color for UI display */
  color?: string
  /** Minimum topup amount for this payment method */
  min_topup?: number
  /** Optional react-icons component name or safe icon URL */
  icon?: string
}

/**
 * Waffo payment method configuration
 */
export interface WaffoPayMethod {
  /** Display name of payment method */
  name: string
  /** Optional icon path */
  icon?: string
  /** Waffo pay method type */
  payMethodType?: string
  /** Waffo pay method name */
  payMethodName?: string
}

/**
 * Topup configuration information
 */
export interface TopupInfo {
  /** Whether online topup is enabled */
  enable_online_topup: boolean
  /** Whether Stripe topup is enabled */
  enable_stripe_topup: boolean
  /** Available payment methods */
  pay_methods: PaymentMethod[]
  /** Minimum topup amount for online topup */
  min_topup: number
  /** Minimum topup amount for Stripe */
  stripe_min_topup: number
  /** Stripe checkout currency */
  stripe_currency?: string
  /** Whether Stripe only accepts configured preset amounts */
  stripe_preset_only?: boolean
  /** AUD face values for en Stripe presets (e.g. [5, 20, 50]) */
  aud_presets?: number[]
  /** CNY face values for zh Stripe presets (e.g. [10, 30, 100]) */
  cny_presets?: number[]
  /** Minimum Stripe charge for custom amounts, in AUD minor units */
  stripe_min_charge_minor?: number
  /** ¥ per $1 credit conversion rate used for CNY presets (e.g. 7.3) */
  usd_exchange_rate?: number
  /** Preset amount options */
  amount_options: number[]
  /** Discount rates by amount */
  discount: Record<number, number>
  /** Optional topup link for purchasing codes */
  topup_link?: string
  /** Whether Creem topup is enabled */
  enable_creem_topup?: boolean
  /** Available Creem products */
  creem_products?: CreemProduct[]
  /** Whether Waffo topup is enabled */
  enable_waffo_topup?: boolean
  /** Available Waffo payment methods */
  waffo_pay_methods?: WaffoPayMethod[]
  /** Minimum topup amount for Waffo */
  waffo_min_topup?: number
  /** Whether Waffo Pancake topup is enabled */
  enable_waffo_pancake_topup?: boolean
  /** Minimum topup amount for Waffo Pancake */
  waffo_pancake_min_topup?: number
  /** Whether redemption code usage is enabled */
  enable_redemption?: boolean
  /** Whether compliance confirmation has been completed */
  payment_compliance_confirmed?: boolean
  /** Current compliance terms version */
  payment_compliance_terms_version?: string
}

/**
 * Display model for one Stripe preset button, derived from the backend's
 * `aud_presets` / `cny_presets` face-value catalogs.
 *
 * `amount_cents` is the credited amount in USD-credit cents (exact int),
 * `charge_cents` is the Stripe charge in AUD minor units — both mirror the
 * server-side arithmetic for preview; the server recomputes them from `id`.
 */
export interface StripePreset {
  /** Stable preset id, e.g. "aud-5" or "cny-10" */
  id: string
  /** Face currency the preset is denominated in */
  currency: 'AUD' | 'CNY'
  /** Face value in the preset currency (5 → A$5, 10 → ¥10) */
  face_value: number
  /** Credited USD credits in cents */
  amount_cents: number
  /** Charged AUD amount in minor units (cents) */
  charge_cents: number
}

/**
 * Stripe checkout request (new contract): either a preset id or a custom
 * credited amount in USD-credit cents.
 */
export interface StripeCheckoutRequest {
  /** Preset id such as "aud-5" / "cny-10" */
  preset?: string
  /** Custom credited amount in USD-credit cents */
  amount_cents?: number
  /** Always "stripe" */
  payment_method: 'stripe'
}

